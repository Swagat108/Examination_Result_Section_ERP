-- PostgreSQL port of db/00_admin.sql (tables, constraints, indexes). MySQL original is unchanged.
-- =====================================================================
-- 00_admin.sql   |  G1 - Communication & Administration
-- Master data (department, program, academic_year, semester, division,
-- batch), login/roles, notices, grievances, app settings.
-- Run first: every other module references these tables.
-- The target database is selected by the caller (db/rebuild.sh|ps1).
-- Cross-module FKs on app_user (student / employee) are added in
-- 07_integration.sql once those tables exist.
-- =====================================================================

-- ---------------------------------------------------------------------
-- TABLES
-- ---------------------------------------------------------------------

CREATE TABLE department (
  dept_code CHAR(3) NOT NULL,
  dept_name VARCHAR(100) NOT NULL,
  dept_type VARCHAR(14) NOT NULL DEFAULT 'ACADEMIC' CHECK (dept_type IN ('ACADEMIC', 'ADMINISTRATIVE')),
  hod_employee_id CHAR(7) NULL,
  established_year SMALLINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_department PRIMARY KEY (dept_code),
  CONSTRAINT uq_department_name UNIQUE (dept_name),
  CONSTRAINT ck_department_code CHECK (dept_code ~ '^[A-Z]{3}$')
);
COMMENT ON TABLE department IS 'G1 master: departments (ETC, CMP, ITX, ...)';

CREATE TABLE program (
  program_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  dept_code CHAR(3) NOT NULL,
  program_code VARCHAR(12) NOT NULL,
  program_name VARCHAR(120) NOT NULL,
  degree_level VARCHAR(8) NOT NULL DEFAULT 'UG' CHECK (degree_level IN ('DIPLOMA', 'UG', 'PG', 'DOCTORAL')),
  duration_years SMALLINT NOT NULL,
  total_semesters SMALLINT NOT NULL,
  sanctioned_intake SMALLINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_program PRIMARY KEY (program_id),
  CONSTRAINT uq_program_code UNIQUE (program_code),
  CONSTRAINT fk_program_dept FOREIGN KEY (dept_code) REFERENCES department (dept_code),
  CONSTRAINT ck_program_duration CHECK (duration_years BETWEEN 1 AND 6),
  CONSTRAINT ck_program_semesters CHECK (total_semesters = duration_years * 2),
  CONSTRAINT ck_program_intake CHECK (sanctioned_intake IS NULL OR sanctioned_intake > 0)
);
COMMENT ON TABLE program IS 'G1 master: degree programs offered by a department';

CREATE TABLE academic_year (
  academic_year_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  label VARCHAR(9) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  is_current SMALLINT NOT NULL DEFAULT 0,
  current_flag SMALLINT GENERATED ALWAYS AS (CASE WHEN is_current = 1 THEN 1 END) STORED,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_academic_year PRIMARY KEY (academic_year_id),
  CONSTRAINT uq_academic_year_label UNIQUE (label),
  CONSTRAINT uq_academic_year_current UNIQUE (current_flag),
  CONSTRAINT ck_academic_year_label CHECK (label ~ '^[0-9]{4}-[0-9]{2}$'),
  CONSTRAINT ck_academic_year_dates CHECK (end_date > start_date)
);
COMMENT ON TABLE academic_year IS 'G1 master: academic years';

CREATE TABLE semester (
  semester_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  academic_year_id INTEGER NOT NULL,
  term VARCHAR(4) NOT NULL CHECK (term IN ('ODD', 'EVEN')),
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  is_active SMALLINT NOT NULL DEFAULT 0,
  active_flag SMALLINT GENERATED ALWAYS AS (CASE WHEN is_active = 1 THEN 1 END) STORED,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_semester PRIMARY KEY (semester_id),
  CONSTRAINT uq_semester_term UNIQUE (academic_year_id, term),
  CONSTRAINT uq_semester_active UNIQUE (active_flag),
  CONSTRAINT fk_semester_ay FOREIGN KEY (academic_year_id) REFERENCES academic_year (academic_year_id),
  CONSTRAINT ck_semester_dates CHECK (end_date > start_date)
);
COMMENT ON TABLE semester IS 'G1 master: a teaching term (odd/even) inside an academic year';

CREATE TABLE division (
  division_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  program_id INTEGER NOT NULL,
  academic_year_id INTEGER NOT NULL,
  year_of_study SMALLINT NOT NULL,
  division_name VARCHAR(20) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_division PRIMARY KEY (division_id),
  CONSTRAINT uq_division UNIQUE (program_id, academic_year_id, division_name),
  CONSTRAINT fk_division_program FOREIGN KEY (program_id) REFERENCES program (program_id),
  CONSTRAINT fk_division_ay FOREIGN KEY (academic_year_id) REFERENCES academic_year (academic_year_id),
  CONSTRAINT ck_division_year CHECK (year_of_study BETWEEN 1 AND 6)
);
COMMENT ON TABLE division IS 'G1 master: class division of a program in an academic year';

CREATE TABLE batch (
  batch_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  division_id INTEGER NOT NULL,
  batch_code VARCHAR(5) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_batch PRIMARY KEY (batch_id),
  CONSTRAINT uq_batch UNIQUE (division_id, batch_code),
  CONSTRAINT fk_batch_division FOREIGN KEY (division_id) REFERENCES division (division_id)
);
COMMENT ON TABLE batch IS 'G1 master: practical/lab batch inside a division';

CREATE TABLE role (
  role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY,
  role_name VARCHAR(30) NOT NULL,
  description VARCHAR(200) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_role PRIMARY KEY (role_id),
  CONSTRAINT uq_role_name UNIQUE (role_name),
  CONSTRAINT ck_role_name CHECK (role_name ~ '^[A-Z_]+$')
);
COMMENT ON TABLE role IS 'G1: ADMIN, FACULTY, STUDENT, ACCOUNTANT, PLACEMENT_OFFICER';

CREATE TABLE app_user (
  user_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  username VARCHAR(50) NOT NULL,
  email VARCHAR(120) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  student_id CHAR(11) NULL,
  employee_id CHAR(7) NULL,
  is_active SMALLINT NOT NULL DEFAULT 1,
  last_login_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_app_user PRIMARY KEY (user_id),
  CONSTRAINT uq_app_user_username UNIQUE (username),
  CONSTRAINT uq_app_user_email UNIQUE (email),
  CONSTRAINT uq_app_user_student UNIQUE (student_id),
  CONSTRAINT uq_app_user_employee UNIQUE (employee_id),
  CONSTRAINT ck_app_user_email CHECK (email ~ '^[^@ ]+@[^@ ]+$'),
  CONSTRAINT ck_app_user_one_ref CHECK (student_id IS NULL OR employee_id IS NULL)
);
COMMENT ON TABLE app_user IS 'G1: login accounts (JWT auth in the backend)';

CREATE TABLE user_role (
  user_id INTEGER NOT NULL,
  role_id SMALLINT NOT NULL,
  assigned_by INTEGER NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id),
  CONSTRAINT fk_user_role_user FOREIGN KEY (user_id) REFERENCES app_user (user_id) ON DELETE CASCADE,
  CONSTRAINT fk_user_role_role FOREIGN KEY (role_id) REFERENCES role (role_id),
  CONSTRAINT fk_user_role_by FOREIGN KEY (assigned_by) REFERENCES app_user (user_id) ON DELETE SET NULL
);
COMMENT ON TABLE user_role IS 'G1: many-to-many user <-> role';

CREATE TABLE user_audit_log (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_id INTEGER NOT NULL,
  action VARCHAR(13) NOT NULL CHECK (action IN ('ROLE_ASSIGNED', 'ROLE_REVOKED', 'DEACTIVATED', 'REACTIVATED')),
  old_value VARCHAR(100) NULL,
  new_value VARCHAR(100) NULL,
  changed_by VARCHAR(100) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_user_audit_log PRIMARY KEY (audit_id),
  CONSTRAINT fk_user_audit_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
);
COMMENT ON TABLE user_audit_log IS 'G1: filled by trg_user_audit, trg_user_role_audit_ins/_del';
CREATE INDEX ix_user_audit_user ON user_audit_log (user_id, created_at);

CREATE TABLE app_setting (
  setting_key VARCHAR(50) NOT NULL,
  setting_value VARCHAR(100) NOT NULL,
  description VARCHAR(200) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_app_setting PRIMARY KEY (setting_key)
);
COMMENT ON TABLE app_setting IS 'G1: business thresholds used by SQL objects (75% attendance, 7 day escalation, ...)';

CREATE TABLE notice (
  notice_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  title VARCHAR(200) NOT NULL,
  body TEXT NOT NULL,
  posted_by INTEGER NOT NULL,
  priority VARCHAR(6) NOT NULL DEFAULT 'NORMAL' CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
  published_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMP NULL,
  is_active SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_notice PRIMARY KEY (notice_id),
  CONSTRAINT fk_notice_user FOREIGN KEY (posted_by) REFERENCES app_user (user_id),
  CONSTRAINT ck_notice_expiry CHECK (expires_at IS NULL OR expires_at > published_at)
);
COMMENT ON TABLE notice IS 'G1: notice board';
CREATE INDEX ix_notice_published ON notice (published_at);

CREATE TABLE notice_target (
  notice_target_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  notice_id INTEGER NOT NULL,
  role_id SMALLINT NULL,
  dept_code CHAR(3) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_notice_target PRIMARY KEY (notice_target_id),
  CONSTRAINT fk_notice_target_notice FOREIGN KEY (notice_id) REFERENCES notice (notice_id) ON DELETE CASCADE,
  CONSTRAINT fk_notice_target_role FOREIGN KEY (role_id) REFERENCES role (role_id),
  CONSTRAINT fk_notice_target_dept FOREIGN KEY (dept_code) REFERENCES department (dept_code)
);
COMMENT ON TABLE notice_target IS 'G1: who a notice is for (role x department)';

CREATE TABLE grievance (
  grievance_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  raised_by INTEGER NOT NULL,
  category VARCHAR(14) NOT NULL DEFAULT 'OTHER' CHECK (category IN ('ACADEMIC', 'FEES', 'HOSTEL', 'EXAM', 'ADMINISTRATION', 'OTHER')),
  subject VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  status VARCHAR(11) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_PROGRESS', 'ESCALATED', 'RESOLVED', 'CLOSED')),
  assigned_to INTEGER NULL,
  escalated_at TIMESTAMP NULL,
  resolved_at TIMESTAMP NULL,
  resolution_remarks VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_grievance PRIMARY KEY (grievance_id),
  CONSTRAINT fk_grievance_raised FOREIGN KEY (raised_by) REFERENCES app_user (user_id),
  CONSTRAINT fk_grievance_assigned FOREIGN KEY (assigned_to) REFERENCES app_user (user_id),
  CONSTRAINT ck_grievance_resolved CHECK (status NOT IN ('RESOLVED','CLOSED') OR resolved_at IS NOT NULL)
);
COMMENT ON TABLE grievance IS 'G1: grievance portal';
CREATE INDEX ix_grievance_status ON grievance (status, created_at);
