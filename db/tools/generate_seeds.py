"""Generate the two data-heavy seed files.

    python -I db/tools/generate_seeds.py

Writes
  db/seed/01_academics_timetable_seed.sql  faculty assignment per offering + the TY E&TC weekly timetable
  db/seed/02_students_seed.sql             322 students, admissions, registrations, elective choices, bulk enrolment

Inputs: db/seed/data/etc_ty_sem5_2026_27.csv (made by extract_roster.py from the roll-call PDF).
Output is deterministic - rerun and commit if the CSV or the timetable rules change.
"""
import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
CSV_PATH = ROOT / 'seed' / 'data' / 'etc_ty_sem5_2026_27.csv'
OUT_TT = ROOT / 'seed' / '01_academics_timetable_seed.sql'
OUT_ST = ROOT / 'seed' / '02_students_seed.sql'

PE1 = {'Cloud Computing (CC)': 'ETC351', 'Digital Image and Video Processing (DIVP)': 'ETC352',
       'Microcontrollers and IoT (MI)': 'ETC353', 'CMOS Analog Circuit Design (CACD)': 'ETC354'}
HONORS = {'Honors: VLSI Design Technology (VLSI-DT)': 'HON301', 'Internet of Things (IoT)': 'HON302',
          'Block Chain Technology (BCT)': 'HON303'}
MDM = {'Maths': 'MDM301', 'Finance': 'MDM302'}
DIVISIONS = ['TY V', 'TY VI', 'TY VII', 'TY VIII']


def q(s):
    return "'" + s.replace("'", "''") + "'"


def emp(n):
    return f'EMP{n:04d}'


# ---------------------------------------------------------------------------
# 1. Faculty assignment + timetable
# ---------------------------------------------------------------------------
def build_timetable():
    assign = []   # (course, division|None, 'CUR'|'PREV', employee)
    slots = []    # (course, division|None, room, batch|None, day, start, end, type)

    theory = ['ETC301', 'ETC302', 'ETC303', 'ETC304']
    for d, div in enumerate(DIVISIONS):
        for c, course in enumerate(theory):
            assign.append((course, div, 'CUR', emp(101 + c * 4 + d)))           # EMP0101..0116
        assign.append(('ETC305', div, 'CUR', emp(117 + d)))                      # lab faculty EMP0117..0120
    for i, course in enumerate(['ETC351', 'ETC352', 'ETC353', 'ETC354', 'ETC355', 'ETC356']):
        assign.append((course, None, 'CUR', emp(101 + i)))                       # PE-1
    for i, course in enumerate(['HON301', 'HON302', 'HON303']):
        assign.append((course, None, 'CUR', emp(107 + i)))                       # honors
    assign.append(('MDM301', None, 'CUR', 'EMP0127'))
    assign.append(('MDM302', None, 'CUR', 'EMP0137'))
    for i, course in enumerate(['ETC201', 'ETC202', 'ETC203', 'ETC204', 'ETC205', 'ETC206']):
        assign.append((course, None, 'PREV', emp(110 + i)))                      # semester 4 history
    for i in range(5):
        assign.append((f'CMP30{i + 1}', None, 'CUR', emp(121 + i)))
        assign.append((f'ITX30{i + 1}', None, 'CUR', emp(131 + i)))

    days = ['MON', 'TUE', 'WED', 'THU', 'FRI']
    morning = [('09:00', '10:00'), ('10:00', '11:00'), ('11:15', '12:15')]
    for d, div in enumerate(DIVISIONS):
        room = f'LH-30{d + 1}'
        for i, day in enumerate(days):                       # 15 lecture cells per division
            for j, (st, en) in enumerate(morning):
                slots.append((theory[(i + j) % 4], div, room, None, day, st, en, 'LECTURE'))
        for b, letter in enumerate('KLMN'):                  # one 2-hour lab per batch, on different days
            slots.append(('ETC305', div, f'LAB-E{d + 1}', f'{letter}{5 + d}', days[(b + d) % 5],
                          '14:00', '16:00', 'LAB'))
    for i in range(6):                                       # PE-1: Tue + Thu afternoon
        for day in ('TUE', 'THU'):
            slots.append((f'ETC35{i + 1}', None, f'LH-40{i + 1}', None, day, '14:00', '15:00', 'LECTURE'))
    for i in range(3):                                       # honors: Wed + Fri, 2 hours
        for day in ('WED', 'FRI'):
            slots.append((f'HON30{i + 1}', None, f'LH-40{7 + i}', None, day, '14:00', '16:00', 'LECTURE'))
    slots.append(('MDM301', None, 'LH-410', None, 'MON', '16:00', '17:00', 'LECTURE'))
    slots.append(('MDM302', None, 'LH-411', None, 'MON', '16:00', '17:00', 'LECTURE'))

    # self-check: no faculty or room double-booked (the SQL trigger would reject it anyway)
    fac = {(c, dv): e for c, dv, _, e in assign}
    seen = set()
    for course, div, room, _batch, day, st, en, _t in slots:
        e = fac[(course, div)]
        for key in (('F', e, day, st), ('R', room, day, st)):
            assert key not in seen, f'clash {key}'
            seen.add(key)
    return assign, slots


def write_timetable():
    assign, slots = build_timetable()
    o = ['-- Generated by db/tools/generate_seeds.py - do not edit by hand.',
         '-- Faculty assigned to every offering + the weekly timetable of the TY E&TC divisions (SAMPLE).',
         'SET NAMES utf8mb4;',
         'SET @sem_cur  = fn_current_semester();',
         "SET @sem_prev = (SELECT s.semester_id FROM semester s JOIN academic_year ay ON ay.academic_year_id = s.academic_year_id"
         " WHERE ay.label = '2025-26' AND s.term = 'EVEN');", '',
         'CREATE TEMPORARY TABLE tmp_assign (course_code VARCHAR(8), division_name VARCHAR(20) NULL,'
         ' sem_kind VARCHAR(4), employee_id CHAR(7));',
         'INSERT INTO tmp_assign VALUES']
    o.append(',\n'.join(f"  ({q(c)}, {q(d) if d else 'NULL'}, {q(k)}, {q(e)})" for c, d, k, e in assign) + ';')
    o += ['',
          'UPDATE course_offering o',
          '  JOIN tmp_assign a ON a.course_code = o.course_code',
          '  LEFT JOIN division d ON d.division_id = o.division_id',
          'SET o.employee_id = a.employee_id',
          "WHERE o.semester_id = IF(a.sem_kind = 'CUR', @sem_cur, @sem_prev)",
          '  AND ((a.division_name IS NULL AND o.division_id IS NULL) OR a.division_name = d.division_name);', '',
          'CREATE TEMPORARY TABLE tmp_slot (course_code VARCHAR(8), division_name VARCHAR(20) NULL, classroom_code VARCHAR(10),'
          ' batch_code VARCHAR(5) NULL, day_of_week VARCHAR(3), start_time TIME, end_time TIME, slot_type VARCHAR(10));',
          'INSERT INTO tmp_slot VALUES']
    o.append(',\n'.join(
        f"  ({q(c)}, {q(dv) if dv else 'NULL'}, {q(r)}, {q(b) if b else 'NULL'}, {q(day)}, {q(st)}, {q(en)}, {q(t)})"
        for c, dv, r, b, day, st, en, t in slots) + ';')
    o += ['',
          '-- trg_timetable_clash validates every row of this insert',
          'INSERT INTO timetable_slot (offering_id, classroom_id, employee_id, batch_id, day_of_week, start_time, end_time, slot_type)',
          'SELECT o.offering_id, c.classroom_id, o.employee_id, b.batch_id, t.day_of_week, t.start_time, t.end_time, t.slot_type',
          '  FROM tmp_slot t',
          '  JOIN course_offering o ON o.course_code = t.course_code AND o.semester_id = @sem_cur',
          '  LEFT JOIN division d   ON d.division_id = o.division_id',
          '  JOIN classroom c       ON c.classroom_code = t.classroom_code',
          '  LEFT JOIN batch b      ON b.batch_code = t.batch_code AND b.division_id = d.division_id',
          ' WHERE (t.division_name IS NULL AND o.division_id IS NULL) OR d.division_name = t.division_name',
          ' ORDER BY o.offering_id, t.day_of_week, t.start_time, t.batch_code;',
          '', 'DROP TEMPORARY TABLE tmp_assign;', 'DROP TEMPORARY TABLE tmp_slot;', '']
    OUT_TT.write_text('\n'.join(o), encoding='utf-8', newline='\n')
    print(f'wrote {OUT_TT.name}: {len(assign)} assignments, {len(slots)} slots')


# ---------------------------------------------------------------------------
# 2. Students
# ---------------------------------------------------------------------------
def title_name(name):
    name = name.replace('-fe', '')          # roll call marks one name with a '-fe' remark; not part of the name
    return ' '.join(w.capitalize() for w in name.split())


def write_students():
    rows = list(csv.DictReader(CSV_PATH.open(encoding='utf-8')))
    assert len(rows) == 322, len(rows)
    vals = []
    for r in rows:
        enrol = r['enrollment_no']
        year = 2000 + int(enrol[1:3])                      # F24ET362 -> 2024, S25ET024 -> 2025
        sid = f'{year}ETC{int(enrol[-3:]):04d}'
        vals.append((sid, enrol, title_name(r['full_name']), year, r['roll_no'], r['division'], r['batch'],
                     PE1[r['pe1']], HONORS.get(r['honors']), MDM.get(r['mdm'])))
    assert len({v[0] for v in vals}) == 322
    nul = lambda x: q(x) if x else 'NULL'
    o = ['-- Generated by db/tools/generate_seeds.py from db/seed/data/etc_ty_sem5_2026_27.csv - do not edit by hand.',
         '-- Source: TY E&TC 2026-27 Sem-V roll call (Final Electives & Honors Course).',
         '-- student_id = admission year + ETC + the serial of the university enrollment no (F24ET362 -> 2024ETC0362).',
         '-- Not in the PDF and therefore left empty: date of birth, gender, phone, address, guardians.',
         'SET NAMES utf8mb4;',
         'SET @sem_cur = fn_current_semester();',
         "SET @prog     = (SELECT program_id FROM program WHERE program_code = 'BTECH-ETC');", '',
         'CREATE TEMPORARY TABLE tmp_roster (',
         '  student_id CHAR(11) NOT NULL PRIMARY KEY, enrollment_no VARCHAR(12) NOT NULL, full_name VARCHAR(120) NOT NULL,',
         '  admission_year SMALLINT UNSIGNED NOT NULL, roll_no VARCHAR(10) NOT NULL, division_name VARCHAR(20) NOT NULL,',
         '  batch_code VARCHAR(5) NOT NULL, pe1_course VARCHAR(8) NOT NULL, honors_course VARCHAR(8) NULL, mdm_course VARCHAR(8) NULL);',
         'INSERT INTO tmp_roster VALUES']
    o.append(',\n'.join(
        f"  ({q(s)}, {q(e)}, {q(n)}, {y}, {q(rn)}, {q(dv)}, {q(b)}, {q(pe)}, {nul(h)}, {nul(m)})"
        for s, e, n, y, rn, dv, b, pe, h, m in vals) + ';')
    o += ['',
          'INSERT INTO student (student_id, enrollment_no, full_name, email, program_id, admission_year)',
          "SELECT student_id, enrollment_no, full_name, CONCAT(LOWER(enrollment_no), '@students.erp.local'), @prog, admission_year",
          '  FROM tmp_roster ORDER BY student_id;', '',
          '-- F.. = first-year admission, S.. = direct second-year admission',
          'INSERT INTO admission (student_id, program_id, academic_year_id, admission_type)',
          "SELECT s.student_id, s.program_id, ay.academic_year_id,",
          "       IF(s.enrollment_no LIKE 'S%', 'DIRECT_SECOND_YEAR', 'REGULAR')",
          '  FROM student s JOIN academic_year ay ON YEAR(ay.start_date) = s.admission_year;', '',
          '-- Semester V of 2026-27: division, practical batch and class roll number',
          'INSERT INTO semester_registration (student_id, semester_id, sem_no, division_id, batch_id, roll_no)',
          'SELECT r.student_id, @sem_cur, 5, dv.division_id, b.batch_id, r.roll_no',
          '  FROM tmp_roster r',
          '  JOIN division dv ON dv.division_name = r.division_name AND dv.program_id = @prog',
          '  JOIN batch b     ON b.division_id = dv.division_id AND b.batch_code = r.batch_code;', '',
          '-- Elective choices from the roll call: PE-1, Honors, MDM',
          "INSERT INTO elective_selection (student_id, semester_id, elective_group, course_code)",
          "SELECT student_id, @sem_cur, 'PE-1', pe1_course FROM tmp_roster;",
          "INSERT INTO elective_selection (student_id, semester_id, elective_group, course_code)",
          "SELECT student_id, @sem_cur, 'HONORS', honors_course FROM tmp_roster WHERE honors_course IS NOT NULL;",
          "INSERT INTO elective_selection (student_id, semester_id, elective_group, course_code)",
          "SELECT student_id, @sem_cur, 'MDM', mdm_course FROM tmp_roster WHERE mdm_course IS NOT NULL;", '',
          '-- Core courses of their division + the chosen electives (one transaction)',
          'CALL sp_bulk_enroll_students(@prog, @sem_cur);', '',
          'DROP TEMPORARY TABLE tmp_roster;', '']
    OUT_ST.write_text('\n'.join(o), encoding='utf-8', newline='\n')
    print(f'wrote {OUT_ST.name}: {len(vals)} students')


if __name__ == '__main__':
    write_timetable()
    write_students()
